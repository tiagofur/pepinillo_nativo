// AppleSignInMac.swift
// Pepinillo — Deep Work Companion for Apple
//
// macOS glue for Sign in with Apple (#962). SwiftUI's SignInWithAppleButton
// fails to present the system authorization window when hosted inside a
// sheet, so we drive ASAuthorizationController manually with an explicit
// presentation anchor. The view keeps its custom glass capsule (matching
// the iOS design); this coordinator only launches the flow and relays the
// result.

#if os(macOS)
import AppKit
import AuthenticationServices
import OSLog

private let appleSignInLogger = Logger(subsystem: "com.pepinillo.app", category: "apple-sign-in")

@MainActor
final class AppleSignInCoordinator: NSObject, ASAuthorizationControllerDelegate, ASAuthorizationControllerPresentationContextProviding {
    static let shared = AppleSignInCoordinator()

    private var completion: ((Result<ASAuthorization, Error>) -> Void)?

    override init() {
        super.init()
    }

    /// Launches the Apple sign-in flow anchored to the frontmost app window.
    /// - Parameters:
    ///   - rawNonce: nonce generated by the caller; only its SHA-256 hash is
    ///     sent to Apple, the raw value stays local for token validation.
    ///   - completion: called on the main actor with the authorization or the
    ///     underlying `ASAuthorizationError`.
    func start(rawNonce: String, completion: @escaping (Result<ASAuthorization, Error>) -> Void) {
        self.completion = completion

        let request = ASAuthorizationAppleIDProvider().createRequest()
        request.requestedScopes = [.fullName, .email]
        request.nonce = AppleAuthHelper.sha256Hex(rawNonce)

        let controller = ASAuthorizationController(authorizationRequests: [request])
        controller.delegate = self
        controller.presentationContextProvider = self
        controller.performRequests()
        appleSignInLogger.info("Apple sign-in flow started")
    }

    func presentationAnchor(for controller: ASAuthorizationController) -> ASPresentationAnchor {
        let anchor = NSApp.keyWindow ?? NSApp.mainWindow ?? NSApp.windows.first { $0.isVisible } ?? ASPresentationAnchor()
        return anchor
    }

    func authorizationController(controller: ASAuthorizationController, didCompleteWithAuthorization authorization: ASAuthorization) {
        appleSignInLogger.info("Apple sign-in completed")
        completion?(.success(authorization))
        completion = nil
    }

    func authorizationController(controller: ASAuthorizationController, didCompleteWithError error: Error) {
        let code = (error as? ASAuthorizationError)?.code
        appleSignInLogger.error("Apple sign-in failed: \(String(describing: code), privacy: .public) \(error.localizedDescription, privacy: .public)")
        completion?(.failure(error))
        completion = nil
    }
}
#endif
